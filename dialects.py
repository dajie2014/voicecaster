SHORT = {"东北话": "东北", "四川话": "四川", "粤语": "粤语", "河南话": "河南",
         "陕西话": "陕西", "山东话": "山东", "天津话": "天津", "闽南话": "闽南",
         "吴语": "吴语"}


def convert_all(text: str):
    """一次给出九种，顺序固定。纯词表替换，离线、几毫秒。"""
    out = []
    for name in ORDER:
        t, n, hits = convert(text, name)
        out.append({"name": name, "short": SHORT.get(name, name),
                    "text": t, "count": n, "hits": hits})
    return out


