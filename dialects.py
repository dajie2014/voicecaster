def detect(text: str, min_hits: int = 2):
    """认一下这段话最像哪一路方言 —— 返回 (方言名, 命中数, 命中的词)。

    2026-11-01 加：朗读单元要自动决定「这段是不是方言，交给 Vox 念」。
    两道保险（照 ROADMAP 里定的）：
      - 至少命中 min_hits 个特征词才认，只蹦一个「干啥」不算；
      - 多路都命中时取命中数最多的，平手取 ORDER 靠前的。
    """
    if not text:
        return "", 0, []
    best, best_hits = "", []
    for name in ORDER:
        feats = FEATURES.get(name)
        if not feats:
            d = DIALECTS.get(name)
            feats = [v for v in d["map"].values() if len(v) >= 2] if d else []
        hits = [w for w in set(feats) if w in text]
        if len(hits) > len(best_hits):
            best, best_hits = name, hits
    if len(best_hits) < min_hits:
        return "", 0, []
    return best, len(best_hits), best_hits
