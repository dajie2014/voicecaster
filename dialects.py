def convert(text: str, dialect: str):
    """把一段普通话换成方言用字。返回 (新文本, 换了几处, 换了哪些词)。

    用「最长匹配」从前往后扫，而不是一个个字符串替换 ——
    逐个 replace 会切出「呒没关系」这种半截话（「没有」换完，剩下的「关系」还挂着）。
    """
    d = DIALECTS.get(dialect)
    if not d or not text:
        return text, 0, []
    table = d["map"]
    keys = sorted(table, key=len, reverse=True)
    out, hits, i = [], [], 0
    while i < len(text):
        hit = None
        for k in keys:
            if text.startswith(k, i):
                hit = k
                break
        if hit:
            out.append(table[hit])
            hits.append(hit + "→" + table[hit])
            i += len(hit)
        else:
            out.append(text[i])
            i += 1
    return "".join(out), len(hits), hits

# 固定顺序（用户 2026-10-30 定，顺序不能乱）
